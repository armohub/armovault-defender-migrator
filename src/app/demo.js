function mockScreenshot(title, rows) {
  const c = document.createElement('canvas');
  c.width = 960; c.height = 420;
  const g = c.getContext('2d');
  g.fillStyle = '#f3f4f6'; g.fillRect(0, 0, 960, 420);
  g.fillStyle = '#1f2937'; g.fillRect(0, 0, 960, 44);
  g.fillStyle = '#ffffff'; g.font = '600 16px Segoe UI, sans-serif'; g.fillText('Microsoft Defender: DEMO MOCK-UP (fictional data, not a real screenshot)', 16, 28);
  g.fillStyle = '#111827'; g.font = '600 20px Segoe UI, sans-serif'; g.fillText(title, 24, 84);
  rows.forEach((r, i) => {
    const y = 112 + i * 44;
    g.fillStyle = i % 2 ? '#ffffff' : '#e5e7eb'; g.fillRect(24, y, 912, 40);
    g.fillStyle = '#111827'; g.font = '15px Segoe UI, sans-serif';
    r.forEach((cell, j) => g.fillText(cell, 40 + j * 300, y + 26));
  });
  g.fillStyle = '#b91c1c'; g.font = '600 14px Segoe UI, sans-serif'; g.fillText('Synthetic image generated by the demo: fictional values only', 24, 400);
  const dataUrl = c.toDataURL('image/png');
  const bin = atob(dataUrl.split(',')[1]);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return bytes;
}

export function buildDemoProject(kb) {
  const p = createProject({ mode: 'tailored', guidance: 'simple', appVersion: APP_VERSION, kbVersion: kb.meta.version });
  p.isDemo = true;
  Object.assign(p.meta, {
    name: 'Sentinel → Defender portal transition (DEMO)', organisation: 'Lakeview Logistics (fictional)', operatorName: 'Alex Example', operatorRole: 'Security architect (fictional)',
    startDate: '2026-09-28', windowStart: '2026-11-17', windowEnd: '2026-11-19',
    environments: [
      { alias: 'LL-SOC-PROD-WEU', kind: 'production', notes: 'Planned primary workspace (fictional)' },
      { alias: 'LL-SOC-PROD-NEU', kind: 'production', notes: 'Secondary workspace (fictional)' },
      { alias: 'LL-SOC-TEST', kind: 'test', notes: 'Separate test tenant (fictional)' },
    ],
    notes: 'Demonstration data. Every name, workspace, ticket and screenshot is invented.',
  });
  const v = kb.meta.version;
  const byId = (id) => kb.checks.find((c) => c.id === id);
  for (const [q, a] of Object.entries(ANSWERS)) setAnswer(p, q, a, a === 'unknown' ? 'Owner to confirm (demo)' : '');
  const evidence = new Map();

  const note = (id, title, text) => addEvidence(p, id, { kind: 'note', title, text, stage: byId(id).stage }, v);
  const link = (id, title, url) => addEvidence(p, id, { kind: 'link', title, url, stage: byId(id).stage }, v);
  const shot = (id, title, rows) => {
    const bytes = mockScreenshot(title, rows);
    const ev = addEvidence(p, id, { kind: 'image', title, fileName: `${id.toLowerCase()}-demo.png`, mime: 'image/png', size: bytes.length, redactionConfirmed: true, text: 'Synthetic mock-up generated by the demo.', stage: byId(id).stage }, v);
    evidence.set(ev.id, { bytes, mime: 'image/png' });
  };
  const pass = (id) => setCheckStatus(p, byId(id), 'passed', { kbVersion: v });
  const status = (id, s, reason) => setCheckStatus(p, byId(id), s, { reason, kbVersion: v });
  const owner = (id, o, due) => { setCheckField(p, id, 'owner', o, v); if (due) setCheckField(p, id, 'due', due, v); };

  note('PREP-SCOPE-01', 'Kick-off briefing', 'Briefing held with SOC, IAM, compliance and ITSM owners. Retirement statement and behaviour changes explained. 3 open questions logged.'); pass('PREP-SCOPE-01');
  status('PREP-SCOPE-02', 'not_verified'); owner('PREP-SCOPE-02', 'Alex Example');
  note('PREP-SCOPE-03', 'Window approved', 'Window 17 to 19 November 2026 approved by the change board (fictional CHG-0042).'); pass('PREP-SCOPE-03');
  shot('PREP-SCOPE-04', 'Settings > Microsoft Sentinel > Workspaces', [['Workspace', 'Status', 'Role'], ['LL-SOC-PROD-WEU', 'Not connected', 'None'], ['LL-SOC-PROD-NEU', 'Not connected', 'None']]); pass('PREP-SCOPE-04');
  note('PREP-TOP-01', 'Workspace inventory', 'Resource Graph query returned 2 production workspaces (WEU, NEU). Test workspace is in a separate tenant.'); pass('PREP-TOP-01');
  note('PREP-TOP-02', 'Primary decision', 'LL-SOC-PROD-WEU chosen as primary: hosts the global SOC and the Defender XDR connector today.'); pass('PREP-TOP-02');
  status('PREP-TOP-03', 'in_progress'); owner('PREP-TOP-03', 'Sam Example', '2026-11-05');
  shot('PREP-ACC-01', 'Role assignments: operator (fictional)', [['Role', 'Scope', 'Condition'], ['Owner', 'Subscription LL-SEC', 'None (unconditional)'], ['Security Administrator', 'Tenant (PIM eligible)', 'None']]); pass('PREP-ACC-01');
  status('PREP-ACC-02', 'in_progress'); owner('PREP-ACC-02', 'Riley Example');
  status('PREP-ACC-04', 'failed', 'IdentityInfo is restricted with table-level RBAC for Tier 1; this cannot be preserved in advanced hunting.');
  link('PREP-GOV-02', 'DPO approval (fictional record)', 'https://example.com/approvals/DPO-2026-017'); pass('PREP-GOV-02');
  note('PREP-GOV-01', 'Locations compared', 'Workspaces in West Europe and North Europe; Defender data storage location EU. Retention differences documented.'); pass('PREP-GOV-01');
  status('PREP-CON-02', 'blocked', 'Waiting for the Defender for Cloud owner to confirm which subscriptions the tenant-based connector should cover.'); owner('PREP-CON-02', 'Defender for Cloud team');
  note('PREP-CON-04', 'Ingestion baseline', 'Usage baseline exported for both workspaces (fictional file baseline-ingestion-weu-20261012.csv). 14 critical tables marked.'); pass('PREP-CON-04');
  status('PREP-CON-06', 'not_verified');
  note('PREP-DET-01', 'Rule inventory', 'Both API versions run: 212 rules (2025-07-01-preview) vs 188 (2025-09-01); difference = NRT and ML rules.'); pass('PREP-DET-01');
  status('PREP-DET-03', 'in_progress'); owner('PREP-DET-03', 'Sam Example', '2026-11-01');
  status('PREP-AUT-01', 'failed', '7 automation rules filter on Incident provider and 3 on incident title. Redesign not yet implemented.'); owner('PREP-AUT-01', 'Automation team', '2026-11-08');
  note('PREP-INT-01', 'ServiceNow mapping reviewed', 'Ticket description and deep link fields mapped; description will be composed in the ticketing playbook.'); status('PREP-INT-01', 'passed');
  status('PREP-OPS-03', 'in_progress'); owner('PREP-OPS-03', 'SOC lead');

  const a1 = addRegisterItem(p, { type: 'action', title: 'Redesign 10 automation rule conditions', checkId: 'PREP-AUT-01', owner: 'Automation team', due: '2026-11-08', severity: 'high', description: 'Replace Incident provider and title conditions with analytic rule name and tags.' });
  addRegisterItem(p, { type: 'issue', title: 'Defender for Cloud connector scope unclear', checkId: 'PREP-CON-02', owner: 'Defender for Cloud team', due: '2026-11-03', severity: 'high' });
  const ex = addRegisterItem(p, { type: 'exception', title: 'IdentityInfo table-level restriction not preserved', checkId: 'PREP-ACC-04', owner: 'IAM lead', severity: 'high', description: 'Tier 1 can see IdentityInfo fields in advanced hunting.' });
  acceptException(p, ex.id, { acceptedBy: 'Jordan Example', acceptedRole: 'CISO (fictional)', rationale: 'Accepted for 90 days; compensating control: Tier 1 access review and monitoring of advanced hunting queries.' });
  addRegisterItem(p, { type: 'decision', title: 'LL-SOC-PROD-WEU is the primary workspace', checkId: 'PREP-TOP-02', owner: 'Alex Example', severity: 'medium', status: 'done' });
  addRegisterItem(p, { type: 'risk', title: 'Analysts rely on Similar incidents for triage', owner: 'SOC lead', severity: 'medium' });
  void a1;

  setTestAvailability(p, 'available', '');
  note('TEST-01', 'Test tenant comparison', 'Separate tenant with Defender XDR E5 trial; 40 representative rules and 6 automation rules copied. No ITSM test instance.'); pass('TEST-01');
  shot('TEST-04', 'Test tenant: workspace connected', [['Workspace', 'Status', 'Role'], ['LL-SOC-TEST', 'Connected', 'Primary']]); pass('TEST-04');
  status('TEST-05', 'in_progress');
  recordGate(p, 'PREP-PLN-05', { decision: 'deferred', decidedBy: 'Jordan Example', decidedRole: 'CISO (fictional)', rationale: 'Re-review after automation redesign and the Defender for Cloud decision.' });
  addAudit(p, 'demo.created', 'Demo project generated with fictional data');
  return { project: p, evidence };
}

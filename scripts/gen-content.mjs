// Generates content modules from repository files so the single-file app can show and download them offline.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const script = fs.readFileSync(path.join(root, 'tools/Get-ArMoSentinelInventory.ps1'), 'utf8').replace(/\r\n/g, '\n');
if (/[^\x00-\x7F]/.test(script)) throw new Error('tools/Get-ArMoSentinelInventory.ps1 must be ASCII-only (Windows PowerShell 5.1 reads BOM-less files as ANSI).');
const out = `// GENERATED by scripts/gen-content.mjs from tools/Get-ArMoSentinelInventory.ps1 (do not edit).\nexport const INVENTORY_SCRIPT = ${JSON.stringify(script)};\n`;
fs.mkdirSync(path.join(root, 'content/generated'), { recursive: true });
fs.writeFileSync(path.join(root, 'content/generated/inventory-script.mjs'), out, 'utf8');
console.log('Generated content/generated/inventory-script.mjs');
